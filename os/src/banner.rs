//! RespOS 内核启动 banner。
//!
//! 在 `mm::init()` 之后、网络初始化与 initproc 入队之前打印一次，且只由 boot
//! hart 调用。朴素版本只显示内核名字，不附加队伍名、比赛信息或彩色装饰。

/// 大 LOGO：ANSI Shadow 风格的 "RESPOS"。
const LOGO: [&str; 6] = [
    "██████╗ ███████╗███████╗██████╗  ██████╗ ███████╗",
    "██╔══██╗██╔════╝██╔════╝██╔══██╗██╔═══██╗██╔════╝",
    "██████╔╝█████╗  ███████╗██████╔╝██║   ██║███████╗",
    "██╔══██╗██╔══╝  ╚════██║██╔═══╝ ██║   ██║╚════██║",
    "██║  ██║███████╗███████║██║     ╚██████╔╝███████║",
    "╚═╝  ╚═╝╚══════╝╚══════╝╚═╝      ╚═════╝ ╚══════╝",
];

/// 打印启动 banner。
pub fn print_boot_banner() {
    println!("");
    for row in LOGO.iter() {
        println!("    {}", row);
    }
    println!("");
}
